def norm(v):
    v=re.sub(r'[٠-٩]',lambda m:str(ord(m.group())-0x660),v)
    v=re.sub(r'[۰-۹]',lambda m:str(ord(m.group())-0x6F0),v)
    v=v.lower()
    v=re.sub('[ً-ْٰـ]','',v)
    v=re.sub('[أإآٱ]','ا',v).replace('ة','ه').replace('ى','ي').replace('ؤ','و').replace('ئ','ي')
    v=re.sub(r'[-_.,/()،؛]',' ',v)
    return re.sub(r'\s+',' ',v).strip()
mk=[norm(v) for v in MFR.values()]
assert len(set(mk))==len(mk),'manufacturer short names collide'

df['company']=df.mfr.map(MFR)
def compact_strength(s):
    s=re.sub(r'\s+','',s).rstrip('.')
    return s
df['key1']=df.name+'|'+df.mfr+'|'+df.packlabel
needs=df.groupby('key1').strength.transform('nunique')>1
df['display']=df.name.str.rstrip()
df.loc[needs,'display']=df.loc[needs,'name']+' '+df.loc[needs,'strength'].map(compact_strength)
df['display']=df['display']+' ('+df.packlabel+')'
df['ident']=df.display.map(norm)+'|'+df.company.map(norm)
# Merge rows that are the same product to a pharmacist (packaging-material variants, repeated ids)
agg=df.sort_values('n').groupby('ident',sort=False).agg(
    display=('display','first'),company=('company','first'),comp=('comp','first'),
    strength=('strength','first'),form=('form','first'),ids=('id',lambda s:'، '.join(str(x) for x in dict.fromkeys(s))),
    packs=('pack',lambda s:' | '.join(dict.fromkeys(s))),rows=('n','count'),mfr=('mfr','first'))
print('catalog items',len(agg),'merged rows',(agg.rows>1).sum(),'from',agg.rows[agg.rows>1].sum())
