const { Schema, model } = require('mongoose');

// A discount code a pharmacy types at checkout. It comes off the order total
// AFTER every other discount (offer, manufacturer, package, platform) - see
// order.service.js's rollUpOrderMoney, and backend/docs/MONEY_FLOW.md §9.
//
// Two owners, two funding models:
//   - a WAREHOUSE code works only on orders to that warehouse, needs an admin's
//     approval before it works, and the warehouse bears the discount;
//   - an ADMIN code works on orders to any warehouse, is live from creation,
//     and the platform bears it: the warehouse is compensated in full through
//     the settlement report (settlement.service.js), never through the ledger.
//
// The string itself is generated by the system (discountCode.service.js) and
// is never edited.

// A warehouse's edit to a code that is ALREADY approved is parked here until
// an admin decides - the same buffer offers use (offer.model.js), so the terms
// a pharmacy already applied in its cart never change mid-review. Only the
// editable terms; the owner, scope and pharmacy are fixed at creation.
const discountCodeUpdateSchema = new Schema(
  {
    type: { type: String, enum: ['percentage', 'fixed'], required: true },
    value: { type: Number, required: true },
    startDate: { type: Date, required: true },
    endDate: { type: Date, required: true },
    maxUses: { type: Number, default: null },
    maxUsesPerPharmacy: { type: Number, default: null },
    requestedAt: { type: Date, default: Date.now },
  },
  { _id: false }
);

const discountCodeSchema = new Schema(
  {
    code: { type: String, required: true },
    ownerRole: { type: String, enum: ['warehouse', 'admin'], required: true },
    // The only warehouse whose orders a warehouse code works on. null on an
    // admin code, which works on every warehouse.
    warehouseId: { type: Schema.Types.ObjectId, ref: 'Warehouse', default: null },
    // null = a general code (any approved pharmacy). Otherwise the one
    // pharmacy allowed to use it.
    pharmacyId: { type: Schema.Types.ObjectId, ref: 'Pharmacy', default: null },
    // 'percentage': `value` is a percent (> 0, <= 100, two decimals).
    // 'fixed': `value` is whole lira (SYP), capped at the order total.
    type: { type: String, enum: ['percentage', 'fixed'], required: true },
    value: { type: Number, required: true },
    startDate: { type: Date, required: true },
    endDate: { type: Date, required: true },
    // null = no limit.
    maxUses: { type: Number, default: null },
    maxUsesPerPharmacy: { type: Number, default: null },
    // Uses currently held by live orders. Claimed with a conditional $inc in
    // the order's own transaction, and handed back when the order is
    // cancelled or fully returned - so it never exceeds maxUses.
    usedCount: { type: Number, default: 0, min: 0 },
    // 'pending' waits for an admin (warehouse codes only); 'rejected' and
    // 'stopped' are final. A code is usable only while 'approved' and inside
    // its date window.
    status: {
      type: String,
      enum: ['pending', 'approved', 'rejected', 'stopped'],
      required: true,
    },
    // Goes up whenever the terms that decide the discount amount (type/value)
    // change on a live code. The cart previews against one revision and sends
    // it back with the order; a different one at submit is
    // DISCOUNT_CODE_CHANGED (reason DISCOUNT_CODE_EDITED). Dates and limits
    // are checked live instead - they either still allow the order or they
    // don't.
    revision: { type: Number, default: 1 },
    pendingUpdate: { type: discountCodeUpdateSchema, default: null },
    // The last admin rejection: of the code itself (status 'rejected') or of a
    // parked edit (the code stays approved with its old terms).
    rejectionNote: { type: String, default: null },
    rejectedAt: { type: Date, default: null },
    approvedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    approvedAt: { type: Date, default: null },
    stoppedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    stoppedByRole: { type: String, enum: ['warehouse', 'admin', null], default: null },
    stoppedAt: { type: Date, default: null },
    // Set the one time a pharmacy-specific code's pharmacy is told it can use
    // it, so an edit approval never notifies twice.
    activationNotifiedAt: { type: Date, default: null },
    createdBy: { type: Schema.Types.ObjectId, ref: 'User', required: true },
  },
  // optimisticConcurrency: an admin's approve/reject/edit is conditional on
  // the version the admin reviewed (exposed as `version`), exactly as offers.
  { timestamps: true, optimisticConcurrency: true }
);

discountCodeSchema.index({ code: 1 }, { unique: true });
// The warehouse's own list, newest first.
discountCodeSchema.index({ warehouseId: 1, _id: -1 });
// The admin views: the admin-owned list and the review queue.
discountCodeSchema.index({ ownerRole: 1, _id: -1 });
discountCodeSchema.index({ status: 1, _id: -1 });

module.exports = model('DiscountCode', discountCodeSchema);
